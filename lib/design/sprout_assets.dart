  /// Resolves an asset path for an ingredient name, or returns null if not found.
  static String? resolve(String rawName) {
    final cleaned = rawName
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z\s]'), '')
        .trim();

    if (_ingredientMap.containsKey(cleaned)) {
      return _ingredientMap[cleaned];
    }

    // Try finding by word tokens (e.g. "chopped tomatoes" -> "tomatoes" or "tomato")
    for (final entry in _ingredientMap.entries) {
      if (cleaned.contains(entry.key)) {
        return entry.value;
      }
    }

    return null;
  }
